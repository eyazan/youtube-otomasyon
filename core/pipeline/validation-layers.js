"use strict";
// Three validation layers for premium production. This adds no new gate: it names the layer of every gate that already
// exists, so a refusal says what kind of problem it is and what it takes to clear it.
//
//   FACTUAL    always blocks. Research below the channel standard, unverified quotes or numbers, the claim ledger, a
//              visual mechanism a person has not declared (IB), a drawing that would show something that did not happen
//              (FR creative fidelity), the owner's research review. Never relaxed, never cleared by code.
//   TECHNICAL  blocks on a hard QA check (resolution, decode, black or frozen frames, loudness, true peak, captions, text
//              layout, real speech, determinism). A WARN is reported, not blocking.
//   CREATIVE   supports the editorial decision; never starves production by itself. The viral score ranks topics (a hard
//              minimum only where its calibration against published Shorts is PREDICTIVE); Creative Director flags and
//              creative checks are advisory. The owner's creative approval (or the signed publication policy) is the
//              creative decision.
// Human approvals (creative, factual, publish, voice, research review, mechanism declaration) stay mandatory and are
// only ever written by the person, with their name; nothing here writes or infers one.
const RULES = [
  ["FACTUAL", /creative fidelity|visual mechanism|research|quote|claim|source|ledger|fact|verified|readiness|HUMAN|narration|number/i],
  ["CREATIVE", /viral score|bucket|not ranked|novelty|creative|hook score/i],
  ["TECHNICAL", /\bQA\b|objective|render|loudness|frame|resolution|caption|decode|determinism|true peak/i],
];
// "already published", "reserved", "excluded" are state, not quality
const STATE = /already published|reserved|excluded|generated by the live|retired/i;

function layerOf(reason) {
  const r = String(reason || "");
  if (STATE.test(r)) return "STATE";
  for (const [layer, re] of RULES) if (re.test(r)) return layer;
  return "FACTUAL"; // unknown reasons fail closed into the strictest layer
}

// a review package's QA split into the layers: technical = hard checks; creative = advisory checks and flags
function packageLayers(pkg) {
  const qa = (pkg && pkg.qa) || {};
  const objective = qa.objective || [];
  return {
    TECHNICAL: { blocking: !qa.objectivePass, failed: objective.filter((c) => c.hard && c.status === "FAIL").map((c) => c.name), warnings: objective.filter((c) => c.status === "WARN").map((c) => c.name) },
    CREATIVE: { blocking: false, advisory: (qa.creative || []).filter((c) => c.status === "WARN" || c.ok === false).map((c) => c.name || c.check) },
  };
}

// group a topic's refusal reasons by layer
function classify(reasons = []) {
  const out = { FACTUAL: [], TECHNICAL: [], CREATIVE: [], STATE: [] };
  for (const r of reasons) out[layerOf(r)].push(r);
  return out;
}

module.exports = { layerOf, classify, packageLayers };
