"use strict";
// Failure Reconstructed on the shared premium studio: the researched case file (icerik/konular) becomes a studio topic,
// readiness uses FR's own ledgers, and the automatic forensic grammar yields a valid storyboard for every ready case.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const path = require("path");
const Adapter = require("../../scripts/bto-studio/adapter");
const Generator = require("../../scripts/bto-studio/auto/failure-reconstructed");
const Validator = require("../../scripts/bto-studio/validate");
const profile = require("../../scripts/bto-studio/profiles/failure-reconstructed.json");
const style = require("../../channels/failure-reconstructed/premium/style-pack.json");

const ROOT = path.join(__dirname, "../..");
function fakeTimeline(script) {
  let t = 0; const words = [], lines = [];
  for (const l of script.lines) { const s = t; for (const w of l.text.split(/\s+/)) { words.push({ line: l.id, text: w, start: t, end: t + 0.3 }); t += 0.38; } lines.push({ id: l.id, start: s, end: t }); t += 0.25; }
  return { duration: t, words, lines };
}
const slugs = fs.readdirSync(path.join(ROOT, "icerik/konular")).map((f) => f.replace(/\.json$/, ""));

test("FR case file -> studio topic: narration from sahneler, CASE FILE facts with the case sources", () => {
  const { topic } = Adapter.loadTopic("failure-reconstructed", "air-france-447-2009");
  assert.equal(topic.id, "FR-air-france-447-2009");
  assert.equal(topic.narration.length, 8);
  assert.ok(topic.facts.every((f) => f.layer === "CASE FILE" && /^https?:\/\//.test(f.url)));
  assert.ok(topic.facts.find((f) => f.role === "case").claim.includes("228"));
  assert.deepEqual(topic.case.zincir.length, 5);
});

test("FR readiness: published, produced, failed, in-review and non-visual blocks are refused; a visual block is not", () => {
  const ledger = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, "icerik", f), "utf8"));
  const published = ledger("yayinlananlar.json").map((p) => p.slug).find((s) => slugs.includes(s));
  const p = Adapter.loadTopic("failure-reconstructed", published); const r = Adapter.readiness(p.channel, p.topic);
  assert.equal(r.ready, false); assert.ok(r.errors.some((e) => /already published/.test(e)));
  for (const f of ["inceleme.json", "engellenen.json"]) for (const [slug, e] of Object.entries(ledger(f))) {
    if (!slugs.includes(slug)) continue; const x = Adapter.loadTopic("failure-reconstructed", slug); const rr = Adapter.readiness(x.channel, x.topic);
    if (f === "inceleme.json" || !/visual/i.test(e.neden)) assert.equal(rr.ready, false, `${slug}: ${e.neden}`);
  }
  const ok = Adapter.loadTopic("failure-reconstructed", "air-france-447-2009"); assert.equal(Adapter.readiness(ok.channel, ok.topic).ready, true);
  assert.equal(Adapter.shadowTolerated(["already generated by the live pipeline"]), true, "the live FR lane's own render can be shadowed");
});

test("FR automatic storyboard: valid for every ready case, follows the case spine, chain scenes travel continuously", () => {
  let ready = 0; const kinds = new Set();
  for (const slug of slugs) {
    const { channel, topic } = Adapter.loadTopic("failure-reconstructed", slug); if (!Adapter.readiness(channel, topic).ready) continue; ready += 1;
    const script = Adapter.studioScript(channel, topic); const sb = Generator.build(script, style, topic); kinds.add(Generator.objectKind(topic));
    const v = Validator.validateStoryboard(sb, { script, timeline: fakeTimeline(script), style, policy: profile.evidencePolicy.validator });
    assert.deepEqual(v.errors, [], slug);
    sb.scenes.forEach((s, k) => { if (k && !(s.transition && s.transition.type === "continuity")) assert.notEqual(s.env, sb.scenes[k - 1].env, `${slug} ${s.id}: plate repeats across a cut`); });
    assert.ok(sb.scenes.every((s) => s.chips.includes("conceptualLabel") && s.chips.includes("factLabel")), `${slug}: RECONSTRUCTION + CASE FILE chips`);
  }
  assert.ok(ready >= 300, `${ready} ready FR cases`); assert.ok(kinds.size >= 10, "object classes follow the case");
  const { channel, topic } = Adapter.loadTopic("failure-reconstructed", "air-france-447-2009"); const sb = Generator.build(Adapter.studioScript(channel, topic), style, topic);
  assert.equal(Generator.objectKind(topic), "aircraft");
  const ids = sb.scenes.map((s) => s.id.replace(/^s\d+-/, "")); assert.equal(ids[0], "hook"); assert.equal(ids[ids.length - 1], "payoff"); assert.ok(ids.includes("chain"));
  assert.ok(sb.scenes[1].layers.some((l) => l.component === "kinetic-type" && l.props.items[0].text === "228 ABOARD"), "the toll is the case file's count");
});

test("FR profile: studio preview only, never auto-publishes, the live workflow does not render premium FR", () => {
  assert.equal(profile.studioRenders, true); assert.equal(profile.publishing.autoPublish, false);
  const wf = fs.readFileSync(path.join(ROOT, ".github/workflows/portfolio-production.yml"), "utf8"); assert.ok(!/FR_PREMIUM_RENDER/.test(wf));
});

test("FR premium shadow: OFF by default, FR_PREMIUM_RENDER=preview only, after the live lane, output never committed", () => {
  const Shadow = require("../../core/pipeline/premium-shadow"); const Channel = require("../../core/channel-context");
  const fr = Channel.getChannel("failure-reconstructed"); let calls = 0; const spawn = (bin, args) => { calls += 1; spawn.args = args; return { status: 0, stdout: "", stderr: "" }; };
  assert.equal(Shadow.run(fr, { id: "FR-air-france-447-2009", slug: "air-france-447-2009" }, {}, spawn), null);
  assert.equal(Shadow.run(fr, { id: "FR-x", slug: "x" }, { IB_PREMIUM_RENDER: "preview" }, spawn), null, "the IB flag does not switch FR on");
  assert.equal(Shadow.run(Channel.getChannel("critical-thread"), { id: "CT-1", slug: "x" }, { FR_PREMIUM_RENDER: "preview" }, spawn), null);
  assert.equal(calls, 0);
  Shadow.run(fr, { id: "FR-air-france-447-2009", slug: "air-france-447-2009" }, { FR_PREMIUM_RENDER: "preview", FR_PREMIUM_MEASURE: "0" }, spawn);
  assert.equal(calls, 1); assert.ok(spawn.args.includes("--shadow") && spawn.args.includes("FR-air-france-447-2009"));
  const src = fs.readFileSync(path.join(ROOT, "shorts-sira.js"), "utf8"); const main = src.slice(src.indexOf("function main()"));
  assert.ok(main.indexOf("premium-shadow") > main.indexOf('asama().outcome("UPLOADED"'), "the shadow runs after the live outcome is recorded");
  assert.equal(require("child_process").spawnSync("git", ["check-ignore", "-q", "channels/failure-reconstructed/premium/FR-new-case/out/review-package.json"], { cwd: ROOT }).status, 0);
  assert.equal(require("child_process").spawnSync("git", ["check-ignore", "-q", "uretim/new-case/premium-shadow.json"], { cwd: ROOT }).status, 0);
});
