#!/usr/bin/env node
"use strict";
// Topic funnel and remediation queue for the premium channels (read-only over research; writes only reports/).
// Every topic of a channel's universe is placed at the FIRST stage it does not clear, with the exact refusals the
// premium lane gives it (core/pipeline/premium-lane.js qualified()), so a blocked topic stays in the inventory with a
// named fix instead of disappearing behind NO_TOPIC:
//   UNRESEARCHED      no sourced facts / narration / case file yet                      -> research
//   RESEARCHED        facts exist, verification incomplete (quotes, claim ledger, status) -> verify sources
//   VERIFIED          verified, but below the channel's appeal bar or script shape        -> rescore / rewrite
//   CREATIVE_VIABLE   viable, but no declared/supported visual mechanism                  -> declare or build drawing
//   RENDERABLE        everything above cleared (lane-qualified)                           -> render for review
//   (PUBLICATION_READY needs a recorded human creative PASS; counted from research/reviews where present)
//   HISTORY           published, generated, reserved or retired: excluded, never re-selected
//   node scripts/growth/topic-funnel.js [--channel impossible-brief] [--write]
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const Channel = require(path.join(ROOT, "core/channel-context"));
const Lane = require(path.join(ROOT, "core/pipeline/premium-lane"));

const STAGES = ["UNRESEARCHED", "RESEARCHED", "VERIFIED", "CREATIVE_VIABLE", "RENDERABLE"];
const RULES = [
  ["HISTORY", /already published|already generated|generated by the live pipeline|reserved for a premium|retired CriticalThread|excluded|in human review|blocked by the live pipeline/i],
  ["UNRESEARCHED", /not researched|has no facts|has no narration|QUESTION_ONLY|no researched case file|not a GoalLore Lab record/i],
  ["RESEARCHED", /NEEDS_PRIMARY_SOURCE|verbatim quote|SOURCE_UNVERIFIED|not VERIFIED|is UNVERIFIED|not productionReady|claim-source ledger/i],
  ["VERIFIED", /viral score|bucket|not ranked|narration lines|lines \(/i],
  ["CREATIVE_VIABLE", /CREATIVE_REVIEW_REQUIRED|visual mechanism|visual pre-check|licensed pictures/i],
];
const FIX = { UNRESEARCHED: "research: sourced facts with verbatim quotes and a narration", RESEARCHED: "verification: claim-source ledger in CI (ib-claim-ledger.yml) / primary source",
  VERIFIED: "packaging: rescore after research, or rewrite the narration to the channel's shape", CREATIVE_VIABLE: "creative: declare topic.visualMechanism (proposal below) or build the missing drawing; never draw an unsupported mechanism" };

// the stage where a topic stops: the first rule it fails (history first: never re-selected)
const stoppedAt = (why) => { if (!why.length) return "RENDERABLE"; if (why.some((w) => RULES[0][1].test(w))) return "HISTORY";
  for (const [stage, re] of RULES.slice(1)) if (why.some((w) => re.test(w))) return stage; return "UNRESEARCHED"; };

// IB: a proposed (not declared) mechanism from the generator's word classifier, for a person to confirm
function proposal(channel, topic) {
  if (channel.slug !== "impossible-brief" || topic.visualMechanism) return null;
  try { const IB = require(path.join(ROOT, "scripts/bto-studio/auto/impossible-brief.js")); const m = IB.mechanismOf ? IB.mechanismOf(topic) : null; const w = m && m.world;
    const byWorld = { rotation: "planet-rotation", orbit: "planet-orbit", magnetic: "magnetic-field", current: "ocean-current", lake: "lake-water", micro: "microbial-population", "earth-interior": "earth-interior", "ocean-depth": "ocean-depth", sky: "atmosphere", body: "human-body", "earth-surface": "earth-surface" };
    return w && byWorld[w] ? { proposed: byWorld[w], basis: `word classifier world "${w}"`, status: "PROPOSED_NOT_DECLARED" } : { proposed: null, basis: "no drawable world matched", status: "NEEDS_CREATIVE_DECISION" }; } catch (e) { return null; }
}

function funnel(slug) {
  const channel = Channel.getChannel(slug); const q = Lane.qualified(channel);
  const rows = [...q.ok.map((r) => ({ ...r, why: [] })), ...q.refused].map((r) => ({ id: r.topic.id, slug: r.topic.slug, priority: r.priority, stage: stoppedAt(r.why), why: r.why, proposal: proposal(channel, r.topic) }));
  const counts = {}; rows.forEach((r) => { counts[r.stage] = (counts[r.stage] || 0) + 1; });
  // remediation queue: closest to production first (one stage away), then by priority
  const order = { CREATIVE_VIABLE: 0, VERIFIED: 1, RESEARCHED: 2, UNRESEARCHED: 3 };
  const queue = rows.filter((r) => r.stage in order).sort((a, b) => order[a.stage] - order[b.stage] || b.priority - a.priority);
  return { channel: slug, name: channel.name, counts, renderable: rows.filter((r) => r.stage === "RENDERABLE"), queue, rows };
}

function markdown(all) {
  const L = ["# Premium topic funnel and remediation queue", "", `Generated ${new Date().toISOString()} by scripts/growth/topic-funnel.js from the premium lane's own refusals. A topic is placed at the first stage it does not clear; nothing is removed from the inventory. RENDERABLE means the lane may render it for review; publication still needs a recorded human creative PASS.`, "",
    "| channel | UNRESEARCHED | RESEARCHED | VERIFIED | CREATIVE_VIABLE | RENDERABLE | HISTORY |", "|---|---|---|---|---|---|---|"];
  for (const f of all) L.push(`| ${f.name} | ${["UNRESEARCHED", "RESEARCHED", "VERIFIED", "CREATIVE_VIABLE", "RENDERABLE", "HISTORY"].map((s) => f.counts[s] || 0).join(" | ")} |`);
  L.push("", "Stage = where the topic stops. Fix for each stage:", ...Object.entries(FIX).map(([k, v]) => `- **${k}**: ${v}`), "");
  for (const f of all) {
    L.push(`## ${f.name}`, "", `Renderable now (${f.renderable.length}): ${f.renderable.slice(0, 12).map((r) => r.id).join(", ") || "none"}`, "", "Remediation queue (top 15, closest to production first):", "", "| topic | stops at | blockers | proposal |", "|---|---|---|---|");
    for (const r of f.queue.slice(0, 15)) L.push(`| ${r.id} | ${r.stage} | ${r.why.slice(0, 3).join("; ").replace(/\|/g, "/").slice(0, 220)} | ${r.proposal ? `${r.proposal.proposed || "-"} (${r.proposal.status})` : ""} |`);
    L.push("");
  }
  return L.join("\n") + "\n";
}

if (require.main === module) {
  const args = process.argv.slice(2); const one = args.includes("--channel") ? [args[args.indexOf("--channel") + 1]] : ["impossible-brief", "failure-reconstructed", "behind-the-ordinary", "goal-lore-lab"];
  const all = one.map(funnel); const md = markdown(all);
  if (args.includes("--write")) { fs.writeFileSync(path.join(ROOT, "reports/premium-topic-funnel.md"), md); fs.writeFileSync(path.join(ROOT, "reports/premium-topic-funnel.json"), JSON.stringify(all.map(({ rows, ...f }) => ({ ...f, rows: rows.map(({ id, stage, why, proposal: p }) => ({ id, stage, why, proposal: p })) })), null, 1) + "\n"); }
  process.stdout.write(md);
}
module.exports = { funnel, stoppedAt, markdown };
