"use strict";
// BTO Premium Studio: script-to-studio adapter.
// Reads an existing researched topic from the channel's topic universe and turns it into the studio's
// narration script, without editing the topic. Readiness is checked here, so a topic that the existing
// pipeline would not produce never reaches the studio:
//   - researchStatus VERIFIED and productionReady (the existing research gate)
//   - every narration line has text, every fact carries a verbatim quote and a source URL
//   - not already published or generated (state/published.json, state/generated.json)
// Each fact gets a stable id (F1..Fn in topic order, plus a short hash of its quote) so storyboard
// scenes can cite the evidence behind what they show.

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const Channel = require("../../core/channel-context");

const ROOT = path.resolve(__dirname, "..", "..");
const sha = (s) => crypto.createHash("sha256").update(String(s)).digest("hex");
const words = (s) => String(s).toLowerCase().replace(/[^a-z0-9 ]+/g, " ").split(/\s+/).filter((w) => w.length > 3);

function readJson(file, fallback) { try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) { return fallback; } }

function loadTopic(channelSlug, idOrSlug) {
  const channel = Channel.getChannel(channelSlug);
  if (channelSlug === "failure-reconstructed") return { channel, topic: loadFailureReconstructed(channel, idOrSlug) };
  const universe = readJson(channel.paths.topicUniverse, null);
  if (!universe) throw new Error(`no topic universe at ${channel.paths.topicUniverse}`);
  const topic = universe.topics.find((t) => t.id === idOrSlug || t.slug === idOrSlug);
  if (!topic) throw new Error(`topic ${idOrSlug} not found in ${path.relative(ROOT, channel.paths.topicUniverse)}`);
  return { channel, topic };
}

// ImpossibleBrief records (scripts/ib-ct-library/build.js) are "researched" rather than VERIFIED/productionReady: every
// fact has a source URL and its numbers were checked against that source's text at research time; facts carry the claim,
// not a stored verbatim quote. The studio keeps that channel standard (it is what the live IB pipeline publishes on) and
// reports the missing quote as a warning. A topic blocked ONLY by the stock-picture pre-check is allowed: the premium
// renderer draws its own visuals; every other block, a publication or an upload keeps it out.
const IB_LAYERS = ["KNOWN SCIENCE", "ESTIMATED CONSEQUENCE", "SPECULATIVE SCENARIO"];
function readinessImpossibleBrief(channel, topic) {
  const errors = [], warnings = [];
  if (!topic.researched || !(topic.facts || []).length) errors.push("topic is not researched (no sourced facts)");
  if (topic.status !== "qualified") errors.push(`topic status is ${topic.status}, not qualified`);
  const narration = Array.isArray(topic.narration) ? topic.narration : [];
  if (narration.length < 5) errors.push(`topic has ${narration.length} narration lines (5-8 required)`);
  narration.forEach((l, i) => { if (!String(l.text || "").trim()) errors.push(`narration line ${i + 1} is empty`); if (!IB_LAYERS.includes(l.layer)) errors.push(`narration line ${i + 1} layer ${l.layer} is not an IB layer`); });
  (topic.facts || []).forEach((f, i) => {
    if (!String(f.claim || "").trim()) errors.push(`fact ${i + 1} has no claim`);
    if (!/^https?:\/\//.test(String(f.url || ""))) errors.push(`fact ${i + 1} has no source URL`);
    if (!IB_LAYERS.includes(f.layer)) errors.push(`fact ${i + 1} layer ${f.layer} is not an IB layer`);
    if (!String(f.quote || "").trim()) warnings.push(`fact ${i + 1}: no stored verbatim quote (IB standard: numbers checked against the source at research time)`);
  });
  const published = readJson(path.join(channel.paths.state, "published.json"), []);
  const generated = readJson(path.join(channel.paths.state, "generated.json"), []);
  const pub = published.filter((p) => p.slug === topic.slug || p.topicId === topic.id);
  if (pub.length) errors.push(`already published (${pub.map((p) => p.videoId).join(", ")})`);
  if (generated.some((g) => g.topicId === topic.id)) errors.push("already generated by the live pipeline");
  const blocked = readJson(path.join(channel.paths.state, "blocked.json"), {});
  const block = Array.isArray(blocked) ? (blocked.includes(topic.id) ? { reason: "legacy" } : null) : blocked[topic.id];
  if (block && !/^visual pre-check/.test(block.reason || "")) errors.push(`blocked by the live pipeline: ${block.reason}`);
  else if (block) warnings.push(`blocked for the stock-picture renderer (${block.reason}); the premium renderer draws its visuals`);
  return { ready: errors.length === 0, errors, warnings, publishedRows: pub.length };
}

// Failure Reconstructed: the researched case file the live pipeline publishes from is icerik/konular/<slug>.json
// (sahneler = the narration, vaka = the case: trigger, mechanism, 5-step chain, timeline, misconception, lesson,
// kaynakca = sources). The topic universe row adds the qualification. Facts are the case-file fields, each with the
// case's source URL; like ImpossibleBrief they carry the researched claim, not a stored verbatim quote (warned).
const FR_LAYER = "CASE FILE";
function loadFailureReconstructed(channel, idOrSlug) {
  const slug = String(idOrSlug).replace(/^FR-/, "");
  const universe = readJson(channel.paths.topicUniverse, { topics: [] });
  const row = (universe.topics || []).find((t) => t.topic_id === slug || t.slug === slug) || null;
  const file = path.join(channel.paths.state, "konular", `${slug}.json`);
  const konu = readJson(file, null);
  if (!konu) throw new Error(`no researched case file at ${path.relative(ROOT, file)}`);
  const v = konu.vaka || {}; const src = (konu.vaka && konu.vaka.kaynakca) || []; const s0 = src[0] || {}; const s1 = src[1] || s0;
  const fact = (role, claim, s = s0) => (String(claim || "").trim() ? { role, claim: String(claim).trim(), source: s.ad || null, url: s.url || null, layer: FR_LAYER } : null);
  const facts = [
    fact("case", `${v.ad || konu.baslik}${v.yil ? ` (${v.yil})` : ""}: ${v.sonuc || ""}${v.sayi ? `. ${v.sayi}` : ""}`),
    fact("trigger", v.tetik), fact("mechanism", v.mekanizma, s1),
    fact("chain", (v.zincir || []).join(" -> ")),
    fact("timeline", (v.zaman || []).map((z) => `${z.t}: ${z.olay}`).join("; ")),
    fact("misconception", v.yanilgi, s1), fact("lesson", v.ders, s1),
  ].filter(Boolean);
  const lines = (konu.sahneler || []).map((sc, i, all) => ({ role: i === 0 ? "HOOK" : i === all.length - 1 ? "PAYOFF" : "BODY", layer: FR_LAYER, text: String(sc.metin || "").trim() }));
  return { id: `FR-${slug}`, slug, title: konu.baslik, topic: v.ad || konu.baslik, coreQuestion: konu.soru || null, hook: konu.hook || null,
    narration: lines, facts, case: v, universeRow: row, licensedImages: (konu.tohum || {}).gorselLisanslari || [], sources: src };
}

function readinessFailureReconstructed(channel, topic) {
  const errors = [], warnings = []; const row = topic.universeRow;
  if (!row) errors.push("topic is not in the Failure Reconstructed topic universe");
  else { if (!/^QUALIFIED/.test(row.qualification_status || "")) errors.push(`qualification ${row.qualification_status}`); if (row.production_ready !== true) errors.push("topic is not production_ready"); }
  if (topic.narration.length < 5) errors.push(`case file has ${topic.narration.length} narration lines (5+ required)`);
  topic.narration.forEach((l, i) => { if (!l.text) errors.push(`narration line ${i + 1} is empty`); });
  if (!(topic.sources || []).some((s) => /^https?:\/\//.test(s.url || ""))) errors.push("case file has no source URL (kaynakca)");
  if (!((topic.case || {}).zincir || []).length) errors.push("case file has no failure chain (vaka.zincir)");
  warnings.push("facts are the researched case-file fields with the case's sources, no stored verbatim quotes (FR live standard)");
  const st = (name, fb) => readJson(path.join(channel.paths.state, name), fb);
  const pub = [].concat(st("yayinlananlar.json", [])).filter((p) => p && p.slug === topic.slug);
  if (pub.length) errors.push(`already published (${pub.map((p) => p.videoId).join(", ")})`);
  if ([].concat(st("uretilenler.json", [])).includes(topic.slug)) errors.push("already generated by the live pipeline");
  if ([].concat(st("basarisiz.json", [])).includes(topic.slug)) errors.push("permanently failed in the live pipeline");
  if (st("inceleme.json", {})[topic.slug]) errors.push(`in human review: ${st("inceleme.json", {})[topic.slug].neden}`);
  const block = st("engellenen.json", {})[topic.slug];
  // a stock-footage visual block does not apply to drawn premium visuals; every other block keeps the topic out
  if (block && /visual|görsel|gorsel/i.test(block.neden || "")) warnings.push(`blocked for the stock renderer (${block.neden}); the premium renderer draws its visuals`);
  else if (block) errors.push(`blocked by the live pipeline: ${block.neden}`);
  return { ready: errors.length === 0, errors, warnings, publishedRows: pub.length };
}

function readiness(channel, topic) {
  if (channel.slug === "impossible-brief") return readinessImpossibleBrief(channel, topic);
  if (channel.slug === "failure-reconstructed") return readinessFailureReconstructed(channel, topic);
  const errors = [], warnings = [];
  if (topic.researchStatus !== "VERIFIED") errors.push(`researchStatus is ${topic.researchStatus}, not VERIFIED`);
  if (topic.productionReady !== true) errors.push("topic is not productionReady");
  const narration = Array.isArray(topic.narration) ? topic.narration : [];
  if (!narration.length) errors.push("topic has no narration");
  narration.forEach((l, i) => { if (!String(l.text || "").trim()) errors.push(`narration line ${i + 1} is empty`); if (l.layer && l.layer !== "VERIFIED FACT") warnings.push(`narration line ${i + 1} layer is ${l.layer}`); });
  const facts = Array.isArray(topic.facts) ? topic.facts : [];
  if (!facts.length) errors.push("topic has no facts");
  facts.forEach((f, i) => {
    if (!String(f.quote || "").trim()) errors.push(`fact ${i + 1} has no verbatim quote`);
    if (!/^https?:\/\//.test(String(f.url || ""))) errors.push(`fact ${i + 1} has no source URL`);
    if (f.layer !== "VERIFIED FACT") errors.push(`fact ${i + 1} layer is ${f.layer}`);
  });
  const published = readJson(path.join(channel.paths.state, "published.json"), []);
  const generated = readJson(path.join(channel.paths.state, "generated.json"), []);
  const pub = published.filter((p) => p.slug === topic.slug || p.topicId === topic.id);
  if (pub.length) errors.push(`already published (${pub.map((p) => p.videoId).join(", ")})`);
  if (generated.some((g) => g.topicId === topic.id && g.uploaded)) errors.push("already generated and uploaded");
  return { ready: errors.length === 0, errors, warnings, publishedRows: pub.length };
}

function factsWithIds(topic) {
  return (topic.facts || []).map((f, i) => ({ id: `F${i + 1}`, hash: sha(f.quote || f.claim).slice(0, 10), ...f }));
}

// Suggested evidence per line: facts sharing the most content words with the line (the Visual Director
// confirms or overrides these in the storyboard; the validator checks whatever the storyboard cites).
function suggestEvidence(lineText, facts) {
  const lw = new Set(words(lineText));
  return facts.map((f) => ({ id: f.id, score: words(f.claim + " " + (f.quote || "")).filter((w) => lw.has(w)).length }))
    .filter((x) => x.score >= 2).sort((a, b) => b.score - a.score).slice(0, 3).map((x) => x.id);
}

// Narration script in the shape narrate-edge.js / the studio narrator read: one beat per narration line.
function studioScript(channel, topic, { pauses = {} } = {}) {
  const facts = factsWithIds(topic);
  const voice = channel.config.voice || {};
  const lines = topic.narration.map((l, i) => ({ id: `L${i + 1}`, role: l.role, layer: l.layer, text: l.text.trim(), evidenceSuggested: suggestEvidence(l.text, facts) }));
  const beats = lines.map((l, i) => ({ id: `b${i + 1}`, rate: voice.rate || "+0%", pauseAfterMs: pauses[l.id] != null ? pauses[l.id] : i === lines.length - 1 ? 0 : (l.role === "CLEAR_PROMISE" || lines[i + 1].role === "PAYOFF") ? 360 : 200, lines: [{ id: l.id, text: l.text }] }));
  return {
    schema: "bto-studio.narration-script.v1",
    channel: channel.slug, topicId: topic.id, slug: topic.slug, title: topic.title, coreQuestion: topic.coreQuestion,
    sourceHash: sha(JSON.stringify(topic.narration)).slice(0, 16),
    voice: { approved: { provider: voice.provider, voice: voice.voice, rate: voice.rate } },
    lines, beats, facts: facts.map(({ id, hash, role, claim, quote, source, url, layer }) => ({ id, hash, role, claim, quote, source, url, layer })),
  };
}

// Pilot topics (studio --pilot <dir>): the topic object comes from the pilot folder and the channel object from the
// channel's own config.json, without the registry, state paths or credentials. Nothing here can make a pilot publishable.
function loadPilot(channelSlug, topic) {
  const base = path.join(ROOT, "channels", channelSlug); const config = readJson(path.join(base, "config.json"), null);
  if (!config || config.slug !== channelSlug) throw new Error(`pilot: channels/${channelSlug}/config.json missing or for another channel`);
  return { channel: { slug: channelSlug, config, paths: { base, state: path.join(base, "state") }, pilot: true }, topic };
}
// Pilot readiness: narration lines and sourced claims are required; missing verbatim quotes are reported (they block
// production, not a pilot); research must be honest about its level (layer) for every fact.
function pilotReadiness(topic) {
  const errors = [], warnings = [];
  if (!Array.isArray(topic.narration) || !topic.narration.length) errors.push("pilot has no narration");
  (topic.narration || []).forEach((l, i) => { if (!String(l.text || "").trim()) errors.push(`narration line ${i + 1} is empty`); });
  if (!Array.isArray(topic.facts) || !topic.facts.length) errors.push("pilot has no facts");
  (topic.facts || []).forEach((f, i) => {
    if (!String(f.claim || "").trim()) errors.push(`fact ${i + 1} has no claim`);
    if (!/^https?:\/\//.test(String(f.url || ""))) errors.push(`fact ${i + 1} has no source URL`);
    if (!f.layer) errors.push(`fact ${i + 1} has no evidence layer`);
    if (!String(f.quote || "").trim()) warnings.push(`fact ${i + 1} has no verbatim quote (blocks production, allowed in a pilot)`); });
  return { ready: errors.length === 0, errors, warnings, publishedRows: 0 };
}

// studio --shadow (a second render of the topic the live lane just produced): the only readiness errors it tolerates are
// "the live lane already produced / uploaded this topic". Any research, evidence or block error still refuses.
function shadowTolerated(errors) {
  return errors.length > 0 && errors.every((e) => /^already generated by the live pipeline$|^already published \(/.test(e));
}

module.exports = { shadowTolerated, FR_LAYER, IB_LAYERS, loadTopic, loadPilot, readiness, pilotReadiness, factsWithIds, suggestEvidence, studioScript };
